class FakeAider:
    """Stands in for aider: applies the given edits, returns a log."""

    def __init__(self, edits: dict[str, str], log: str = "Tokens: 4.2k sent, 583 received.\n"):
        self.edits, self.log, self.commands = edits, log, []

    def __call__(self, cmd: list[str], repo: Path) -> str:
        self.commands.append(cmd)
        for rel, text in self.edits.items():
            (repo / rel).write_text(text)
        return self.log


class FakeChecker:
    """Fails on the first call (the unchanged code), then returns `ok` (after aider)."""

    def __init__(self, ok: bool, before: bool = False, leave_behind: str | None = None):
        self.ok, self.before, self.leave_behind, self.calls = ok, before, leave_behind, 0

    def __call__(self, check: str, repo: Path) -> tuple[bool, str]:
        self.calls += 1
        if self.leave_behind:
            (repo / self.leave_behind).write_text("generated by the check\n")
        ok = self.before if self.calls == 1 else self.ok
        return ok, "CHECK OK" if ok else "1 test failed"


def checker(ok: bool) -> FakeChecker:
    return FakeChecker(ok)


def run(repo, task, tmp_path, *, models=lambda: QWEN, aider=None, ok=True):
    return worker.work(
        repo,
        task,
        "make check",
        ["src/a.py"],
        [],
        models=models,
        aider=aider or FakeAider({"src/a.py": "x = 2\n"}),
        checker=checker(ok),
        log_dir=tmp_path / "logs",
    )


