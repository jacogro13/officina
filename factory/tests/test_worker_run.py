def test_aider_only_sees_the_named_files(tmp_path):
    cmd = worker.aider_command(
        tmp_path / "t.md", "make check", ["backend/Dockerfile"], [], tmp_path, tmp_path
    )

    ignore = Path(cmd[cmd.index("--aiderignore") + 1])
    assert ignore.read_text().splitlines() == ["*", "!*/", "!/backend/Dockerfile"]
    assert repo_independent(ignore, tmp_path)


def repo_independent(path: Path, history_dir: Path) -> bool:
    return history_dir in path.parents


@pytest.mark.parametrize(
    ("path", "visible"),
    [
        ("backend/Dockerfile", True),
        ("backend/entrypoint.sh", True),
        ("backend/uv.lock", False),
        ("backend/sub/Dockerfile", False),
        ("pyproject.toml", False),
    ],
)
def test_the_ignore_list_hides_everything_else(repo, path, visible):
    # git understands the same syntax as .aiderignore: let git judge the generated list
    ignore = repo / ".probe-ignore"
    ignore.write_text(worker.aiderignore_text(["backend/Dockerfile", "backend/entrypoint.sh"]))

    probe = subprocess.run(
        ["git", "-c", f"core.excludesFile={ignore}", "check-ignore", "--no-index", "-q", path],
        cwd=repo,
        check=False,
    )

    assert (probe.returncode != 0) is visible
