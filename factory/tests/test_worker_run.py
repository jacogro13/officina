# ── Clean tree and scope ──────────────────────────────────────────────────────


def test_refuses_a_dirty_tree_without_running_aider(repo, task, tmp_path):
    (repo / "src" / "other.py").write_text("y = 3\n")  # someone else's change
    aider = FakeAider({"src/a.py": "x = 2\n"})

    result = run(repo, task, tmp_path, aider=aider)

    assert result.status == "refused"
    assert aider.commands == []
    assert (repo / "src" / "other.py").read_text() == "y = 3\n"  # left untouched


def test_editing_a_file_outside_the_task_reverts_everything(repo, task, tmp_path):
    aider = FakeAider({"src/a.py": "x = 2\n", "src/other.py": "y = 99\n"})

    result = run(repo, task, tmp_path, aider=aider)

    assert result.status == "scope_violation"
    assert "src/other.py" in result.detail
    assert (repo / "src" / "a.py").read_text() == "x = 1\n"
    assert (repo / "src" / "other.py").read_text() == "y = 2\n"


def test_creating_a_file_outside_the_task_is_a_violation_and_is_removed(repo, task, tmp_path):
    aider = FakeAider({"src/a.py": "x = 2\n", "src/sneaky.py": "z = 1\n"})

    result = run(repo, task, tmp_path, aider=aider)

    assert result.status == "scope_violation"
    assert not (repo / "src" / "sneaky.py").exists()


