def test_aider_writes_nothing_of_its_own_into_the_repo(repo, task, tmp_path):
    aider = FakeAider({"src/a.py": "x = 2\n"})

    run(repo, task, tmp_path, aider=aider)

    cmd = aider.commands[0]
    for flag in ("--chat-history-file", "--input-history-file"):
        history = Path(cmd[cmd.index(flag) + 1])
        assert repo not in history.parents


